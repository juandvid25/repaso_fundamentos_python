# Programa: Operador condicional ternario
# Descripción:
# Este programa utiliza el operador ternario para
# determinar si una persona es mayor o menor de edad.

# Variable
edad = 17

# Asigna un mensaje según la edad
mensaje = "Eres mayor de edad." if edad >= 18 else "Eres menor de edad."

# Muestra el resultado
print(mensaje)
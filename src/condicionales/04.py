# Programa: Verificar si una persona puede votar
# Descripción:
# Este programa determina si una persona tiene la edad mínima
# para participar en las elecciones.

# Variable que almacena la edad
edad = 17

# Verifica si la persona tiene 18 años o más
if edad >= 18:
    print("Puedes votar en las elecciones.")
else:
    print("Aún no tienes edad para votar.")
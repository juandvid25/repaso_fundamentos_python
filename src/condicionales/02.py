# Programa: Verificar la temperatura
# Descripción:
# Este programa determina si la temperatura es mayor a 25 grados.
# Si la condición se cumple, muestra el mensaje "Hace calor hoy."

# Variable que almacena la temperatura
temperatura = 30

# Verifica si la temperatura es mayor a 25
if temperatura > 25:
    print("Hace calor hoy.")
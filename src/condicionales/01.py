# Programa: Verificar si una persona es mayor de edad
# Descripción:
# Este programa evalúa si una persona tiene 18 años o más.
# Si la condición se cumple, muestra el mensaje "Mayor de edad".

# Variable que almacena la edad
edad = 20

# Condición para verificar si la persona es mayor de edad
if edad >= 18:
    print("Mayor de edad")
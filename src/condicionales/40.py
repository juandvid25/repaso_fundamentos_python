# Programa: Verificación de elementos con any()
# Descripción:
# Este programa utiliza la función any() para comprobar
# si existe al menos un valor equivalente a True en la lista.

# Variable
numeros = [0, 0, 1, 0]

# Comprueba la presencia de elementos no nulos
if any(numeros):
    print("Al menos un número es no cero.")
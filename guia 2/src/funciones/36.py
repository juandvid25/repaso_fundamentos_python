# Programa: Conversión de Fahrenheit a Celsius
# Descripción:
# Este programa define una función que convierte una
# temperatura expresada en grados Fahrenheit a grados Celsius.

# Función que convierte una temperatura de Fahrenheit a Celsius
def convertir_a_celsius(fahrenheit):
    """
    Convierte una temperatura de Fahrenheit a Celsius.
    """

    # Devuelve la temperatura convertida a grados Celsius
    return (fahrenheit - 32) * 5 / 9
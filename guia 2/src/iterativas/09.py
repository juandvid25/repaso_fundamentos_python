# Programa: Contar del 1 al 5 con un ciclo while
# Descripción:
# Este programa utiliza un ciclo while para
# mostrar los números del 1 al 5 de forma
# consecutiva.

# Inicializa el contador
contador = 1

# Repite el ciclo mientras el contador sea menor o igual a 5
while contador <= 5:
    print(contador)

    # Incrementa el contador en 1
    contador += 1
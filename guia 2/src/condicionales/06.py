# Programa: Verificar si un número es par o impar
# Descripción:
# Este programa determina si un número es par o impar
# utilizando el operador módulo (%).

# Variable que almacena el número
numero = 15

# Verifica si el número es divisible entre 2
if numero % 2 == 0:
    print("El número es par.")
else:
    print("El número es impar.")
# Programa: Identificar un color
# Descripción:
# Este programa compara el valor de una variable
# con diferentes colores utilizando if y elif.

# Variable que almacena el color
color = "azul"

# Compara el color
if color == "rojo":
    print("El color es rojo.")
elif color == "verde":
    print("El color es verde.")
elif color == "azul":
    print("El color es azul.")
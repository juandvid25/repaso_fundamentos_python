# Programa: Clasificar un número
# Descripción:
# Este programa determina si un número es positivo,
# negativo o igual a cero.

# Variable que almacena el número
numero = 0

# Evalúa el valor del número
if numero > 0:
    print("El número es positivo.")
elif numero < 0:
    print("El número es negativo.")
else:
    print("El número es cero.")
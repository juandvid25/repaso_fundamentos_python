# Descripción:
# Este programa muestra una figura con forma de flecha utilizando
# la función print(). También incluye un ejemplo comentado para
# duplicar la figura horizontalmente.

# -------------------------------
# Ejemplo de flecha duplicada
# (Cada línea se multiplica por 2)
# -------------------------------

print(("    *       ") * 2)
print(("   * *      ") * 2)
print(("  *   *     ") * 2)
print((" *     *    ") * 2)
print(("***   ***   ") * 2)
print(("  *   *     ") * 2)
print(("  *   *     ") * 2)
print(("  *****     ") * 2)

# -------------------------------
# Flecha utilizando un solo print()
# \n representa un salto de línea.
# -------------------------------

print("   *\n  *  *\n *   *\n *   *\n ***   ***\n *  *\n *  *\n *****")
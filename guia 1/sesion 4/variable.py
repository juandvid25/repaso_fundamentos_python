# Declaración de variables

# Se asignan valores a tres variables numéricas.
numero1 = 20
numero2 = 8
numero3 = 3

# Operaciones aritméticas

# Calcula la suma de los tres números.
suma = numero1 + numero2 + numero3

# Calcula la resta de los tres números.
resta = numero1 - numero2 - numero3

# Calcula la multiplicación de los tres números.
multiplicacion = numero1 * numero2 * numero3

# Calcula la división de los tres números.
division = numero1 / numero2 / numero3

# Calcula la división entera (sin decimales).
division_entera = numero1 // numero2 // numero3

# Mostrar los valores iniciales

# Imprime el valor de cada número.
print("Número 1:", numero1)
print("Número 2:", numero2)
print("Número 3:", numero3)

# Mostrar los resultados

# Imprime el resultado de cada operación realizada.
print("\nResultados de las operaciones:")
print("Suma:", suma)
print("Resta:", resta)
print("Multiplicación:", multiplicacion)
print("División:", division)
print("División entera:", division_entera)

# Uso de otra variable

# Se crea una variable con el total de manzanas.
